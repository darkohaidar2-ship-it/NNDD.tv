export const FONT_STORAGE_KEY = 'nndd_app_font';

/**
 * Apply a font by ID directly to the document root and save to localStorage
 */
export function applyFontToDocument(fontId) {
  const font = AVAILABLE_FONTS.find(f => f.id === fontId) || AVAILABLE_FONTS[0];
  document.documentElement.style.setProperty('--app-font', font.fontFamily);
  try {
    localStorage.setItem(FONT_STORAGE_KEY, font.id);
  } catch (e) {
    console.warn('Could not save font to localStorage:', e);
  }
  return font;
}

/**
 * Get current saved font from localStorage
 */
export function getCurrentFont() {
  try {
    const saved = localStorage.getItem(FONT_STORAGE_KEY);
    if (saved) {
      const match = AVAILABLE_FONTS.find(f => f.id === saved);
      if (match) return match;
    }
  } catch (e) {}
  return AVAILABLE_FONTS[0];
}
